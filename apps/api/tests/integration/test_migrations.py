async def _version_graph(
    db: AsyncSession,
) -> tuple[Chunk, Transcript, IndexGeneration, Any]:
    actor = await make_actor(db)
    audio, _attempt, transcript = await make_class_with_transcript(db, actor)
    generation = IndexGeneration(
        user_id=actor.user_id,
        version="integrity-v1",
        model="test-model",
        dimension=1536,
        status="building",
    )
    db.add(generation)
    await db.flush()
    chunk = Chunk(
        user_id=actor.user_id,
        audio_id=audio.id,
        transcript_id=transcript.id,
        transcript_version=transcript.version,
        index_version=generation.version,
        ordinal=1,
        content="texto indexado",
        char_start=0,
        char_end=len("texto indexado"),
        token_count=2,
    )
    db.add(chunk)
    await db.flush()
    return chunk, transcript, generation, actor


async def test_version_invariants_are_enforced_by_the_database(
    db_session: AsyncSession,
) -> None:
    chunk, transcript, generation, actor = await _version_graph(db_session)

    # A chunk cannot name a generation that does not exist.
    async with db_session.begin_nested():
        db_session.add(
            Chunk(
                user_id=actor.user_id,
                audio_id=chunk.audio_id,
                transcript_id=transcript.id,
                transcript_version=transcript.version,
                index_version="missing-generation",
                ordinal=1,
                content="huérfano",
                char_start=0,
                char_end=8,
                token_count=1,
            )
        )
        with pytest.raises(IntegrityError):
            await db_session.flush()

    # A chunk cannot claim another transcript version than its transcript row.
    async with db_session.begin_nested():
        db_session.add(
            Chunk(
                user_id=actor.user_id,
                audio_id=chunk.audio_id,
                transcript_id=transcript.id,
                transcript_version=transcript.version + 1,
                index_version=generation.version,
                ordinal=2,
                content="versión falsa",
                char_start=0,
                char_end=14,
                token_count=2,
            )
        )
        with pytest.raises(IntegrityError):
            await db_session.flush()

    # An embedding must sit under its chunk's exact index generation.
    async with db_session.begin_nested():
        db_session.add(
            Embedding(
                user_id=actor.user_id,
                chunk_id=chunk.id,
                index_version="other-generation",
                model="test-model",
                dimension=1536,
                vector=[0.0] * 1536,
            )
        )
        with pytest.raises(IntegrityError):
            await db_session.flush()

    # The dimension is fixed to the vector column's 1536, not a free integer.
    async with db_session.begin_nested():
        db_session.add(
            Embedding(
                user_id=actor.user_id,
                chunk_id=chunk.id,
                index_version=generation.version,
                model="test-model",
                dimension=8,
                vector=[0.0] * 1536,
            )
        )
        with pytest.raises(IntegrityError):
            await db_session.flush()

    async with db_session.begin_nested():
        db_session.add(
            IndexGeneration(
                user_id=actor.user_id,
                version="wrong-dimension",
                model="test-model",
                dimension=8,
                status="building",
            )
        )
        with pytest.raises(IntegrityError):
            await db_session.flush()

    # A delivered citation names the exact transcript version it saw.
    conversation = await make_conversation(db_session, actor)
    message = Message(
        user_id=actor.user_id, conversation_id=conversation.id, role="assistant"
    )
    db_session.add(message)
    await db_session.flush()
    async with db_session.begin_nested():
        db_session.add(
            MessageSource(
                user_id=actor.user_id,
                message_id=message.id,
                kind="transcript",
                audio_id=chunk.audio_id,
                transcript_id=transcript.id,
                transcript_version=transcript.version + 1,
                chunk_id=chunk.id,
            )
        )
        with pytest.raises(IntegrityError):
            await db_session.flush()


