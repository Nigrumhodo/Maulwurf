def test_downgrade_and_upgrade_again(empty_schema: str) -> None:
    cfg = alembic_config(empty_schema)
    revision = ScriptDirectory.from_config(cfg).get_revision(_head(empty_schema))
    assert revision is not None
    parent = revision.down_revision
    assert parent == "0008"  # this chain is linear
    command.upgrade(cfg, "head")

    # `0009` only adds indexes, FKs and CHECKs (no table/column change); `0008` only adds the
    # manual-sync cooldown column; `0007` only adds the mirror and the coverage columns;
    # `0006` only adds `settings`; `0005` only changes roles, policies and RLS flags; `0003`
    # only backfills `chunks.tsv` (data, not schema) and `0004` only adds the run fencing
    # token, so the steps back stay on the previous schemas and only remove those additions.
    command.downgrade(cfg, "-1")
    assert _state(empty_schema) == (S3_TABLES, ["0008"])

    command.downgrade(cfg, "-1")
    assert _state(empty_schema) == (S3_TABLES, ["0007"])
    assert _rls_state(empty_schema) == {"subjects": (True, True), "users": (True, True)}

    command.downgrade(cfg, "-1")
    assert _state(empty_schema) == (S2_TABLES | {"settings"}, ["0006"])
    assert _rls_state(empty_schema) == {"subjects": (True, True), "users": (True, True)}

    command.downgrade(cfg, "-1")
    assert _state(empty_schema) == (S2_TABLES, ["0005"])
    assert _rls_state(empty_schema) == {"subjects": (True, True), "users": (True, True)}

    command.downgrade(cfg, "-1")
    assert _state(empty_schema) == (S2_TABLES, ["0004"])
    assert _processing_run_fencing_token(empty_schema) == ("bigint", "NO", "0")
    assert _rls_state(empty_schema) == {"subjects": (False, False), "users": (False, False)}

    command.downgrade(cfg, "-1")
    assert _state(empty_schema) == (S2_TABLES, ["0003"])
    assert _processing_run_fencing_token(empty_schema) is None

    command.downgrade(cfg, "-1")
    assert _state(empty_schema) == (S2_TABLES, ["0002"])

    command.downgrade(cfg, "-1")
    assert _state(empty_schema) == (S1_TABLES, ["0001"])

    command.upgrade(cfg, "head")
    assert _state(empty_schema)[0] == S3_TABLES


def test_rls_revision_round_trips(empty_schema: str) -> None:
    cfg = alembic_config(empty_schema)
    command.upgrade(cfg, "0004")
    assert _rls_state(empty_schema) == {"subjects": (False, False), "users": (False, False)}

    command.upgrade(cfg, "head")
    assert _rls_state(empty_schema) == {"subjects": (True, True), "users": (True, True)}
    # 0005 grants the runtime roles the data tables, not Alembic's bookkeeping table:
    # SELECT stays for diagnostics, every write is revoked.
    assert _alembic_version_privileges(empty_schema, "maulwurf_app") == {
        "select": True,
        "insert": False,
        "update": False,
        "delete": False,
    }

    command.downgrade(cfg, "0004")
    assert _rls_state(empty_schema) == {"subjects": (False, False), "users": (False, False)}
    # The downgrade revokes every grant (the roles themselves stay cluster-wide).
    assert _alembic_version_privileges(empty_schema, "maulwurf_app") == {
        "select": False,
        "insert": False,
        "update": False,
        "delete": False,
    }

    command.upgrade(cfg, "head")
    assert _alembic_version_privileges(empty_schema, "maulwurf_app") == {
        "select": True,
        "insert": False,
        "update": False,
        "delete": False,
    }


