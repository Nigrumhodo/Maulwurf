def _state(url: str) -> tuple[set[str], list[str]]:
    """Tablas de la app y filas de `alembic_version`."""

    async def read() -> tuple[set[str], list[str]]:
        engine = create_async_engine(url)
        async with engine.connect() as conn:
            tables = set(
                (
                    await conn.execute(
                        text("SELECT tablename FROM pg_tables WHERE schemaname = 'public'")
                    )
                ).scalars()
            )
            versions: list[str] = []
            if "alembic_version" in tables:
                result = await conn.execute(text("SELECT version_num FROM alembic_version"))
                versions = list(result.scalars())
        await engine.dispose()
        return tables - {"alembic_version"}, versions

    return asyncio.run(read())


def _rls_state(url: str) -> dict[str, tuple[bool, bool]]:
    """(ENABLE, FORCE) for two representative tables, from the catalog."""

    async def read() -> dict[str, tuple[bool, bool]]:
        engine = create_async_engine(url)
        async with engine.connect() as conn:
            rows = (
                await conn.execute(
                    text(
                        "SELECT c.relname, c.relrowsecurity, c.relforcerowsecurity "
                        "FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace "
                        "WHERE n.nspname = 'public' AND c.relkind = 'r' "
                        "AND c.relname IN ('subjects', 'users')"
                    )
                )
            ).all()
        await engine.dispose()
        return {
            str(row[0]): (bool(row[1]), bool(row[2]))
            for row in rows
        }

    return asyncio.run(read())


def _alembic_version_privileges(url: str, role: str) -> dict[str, bool]:
    """Privileges of a runtime role on `alembic_version`, from the real catalog."""

    async def read() -> dict[str, bool]:
        engine = create_async_engine(url)
        async with engine.connect() as conn:
            row = (
                await conn.execute(
                    text(
                        "SELECT "
                        "has_table_privilege(:role, 'public.alembic_version', 'SELECT'), "
                        "has_table_privilege(:role, 'public.alembic_version', 'INSERT'), "
                        "has_table_privilege(:role, 'public.alembic_version', 'UPDATE'), "
                        "has_table_privilege(:role, 'public.alembic_version', 'DELETE')"
                    ),
                    {"role": role},
                )
            ).one()
        await engine.dispose()
        return {
            privilege: bool(granted)
            for privilege, granted in zip(
                ("select", "insert", "update", "delete"), row, strict=True
            )
        }

    return asyncio.run(read())


def _processing_run_fencing_token(url: str) -> tuple[str, str, str] | None:
    """Tipo, nulabilidad y default de `processing_runs.fencing_token` (None si no existe)."""

    async def read() -> tuple[str, str, str] | None:
        engine = create_async_engine(url)
        async with engine.connect() as conn:
            row = (
                await conn.execute(
                    text(
                        "SELECT data_type, is_nullable, column_default "
                        "FROM information_schema.columns "
                        "WHERE table_schema = 'public' AND table_name = 'processing_runs' "
                        "AND column_name = 'fencing_token'"
                    )
                )
            ).one_or_none()
        await engine.dispose()
        return None if row is None else (str(row[0]), str(row[1]), str(row[2]))

    return asyncio.run(read())


def _s2_catalog(url: str) -> tuple[dict[str, set[str]], dict[str, str], set[str]]:
    """Constraints, índices y columnas reales; no depende de metadata ORM."""

    async def read() -> tuple[dict[str, set[str]], dict[str, str], set[str]]:
        engine = create_async_engine(url)
        async with engine.connect() as conn:
            constraints = await conn.execute(
                text(
                    "SELECT conrelid::regclass::text, pg_get_constraintdef(oid) "
                    "FROM pg_constraint WHERE connamespace = 'public'::regnamespace"
                )
            )
            indexes = await conn.execute(
                text("SELECT indexname, indexdef FROM pg_indexes WHERE schemaname = 'public'")
            )
            audio_columns = await conn.execute(
                text(
                    "SELECT column_name FROM information_schema.columns "
                    "WHERE table_schema = 'public' AND table_name = 'audios'"
                )
            )
        await engine.dispose()
        foreign_keys: dict[str, set[str]] = {}
        for table_name, definition in constraints:
            if str(definition).startswith("FOREIGN KEY"):
                foreign_keys.setdefault(str(table_name), set()).add(str(definition))
        return (
            foreign_keys,
            {str(name): str(definition) for name, definition in indexes},
            set(audio_columns.scalars()),
        )

    return asyncio.run(read())


